#!/usr/bin/env python3
from __future__ import annotations

import argparse
import re
import subprocess
from pathlib import Path


PROJECT_ROOT = Path(__file__).resolve().parents[2]


def get_ffmpeg_binary() -> str:
    try:
        import imageio_ffmpeg

        return imageio_ffmpeg.get_ffmpeg_exe()
    except ImportError:
        return "ffmpeg"


def clip_to_keyframe_dir(video_path: Path) -> str:
    match = re.search(r"_dia(\d+)_u(\d+)", video_path.stem)
    if not match:
        return video_path.stem
    dia_id, utt_id = match.groups()
    return f"dia{dia_id}utt{utt_id}"


def extract_i_frames(
    video_path: Path,
    output_dir: Path,
    ffmpeg_binary: str,
    overwrite: bool,
) -> bool:
    output_dir.mkdir(parents=True, exist_ok=True)
    if not overwrite and any(output_dir.glob("*.jpg")):
        return True

    if overwrite:
        for old_file in output_dir.glob("*.jpg"):
            old_file.unlink()

    temp_pattern = str(output_dir / "temp_%04d.jpg")
    cmd = [
        ffmpeg_binary,
        "-i",
        str(video_path),
        "-vf",
        r"select=eq(pict_type\,I)",
        "-vsync",
        "vfr",
        "-q:v",
        "2",
        "-loglevel",
        "error",
        "-y",
        temp_pattern,
    ]
    try:
        subprocess.run(cmd, check=True)
        return True
    except subprocess.CalledProcessError:
        return False


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Extract I-frame keyframes from MESC-FT dialogue-history clips."
    )
    parser.add_argument(
        "--input_dir",
        type=Path,
        default=PROJECT_ROOT / "clips",
        help="Directory containing cut clips generated by process_data.py.",
    )
    parser.add_argument(
        "--output_dir",
        type=Path,
        default=PROJECT_ROOT / "keyframes",
        help="Directory where keyframes will be written.",
    )
    parser.add_argument(
        "--overwrite",
        action="store_true",
        help="Overwrite existing jpg files in each output keyframe directory.",
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    ffmpeg_binary = get_ffmpeg_binary()

    if not args.input_dir.exists():
        raise FileNotFoundError(f"Input clip directory not found: {args.input_dir}")

    videos = sorted(args.input_dir.rglob("*.mp4"), key=lambda p: p.name)
    if not videos:
        print(f"No .mp4 clips found under: {args.input_dir}")
        return

    args.output_dir.mkdir(parents=True, exist_ok=True)
    print(f"ffmpeg: {ffmpeg_binary}")
    print(f"input clips: {args.input_dir}")
    print(f"output keyframes: {args.output_dir}")
    print(f"found {len(videos)} clips")

    success_count = 0
    for idx, video_path in enumerate(videos, start=1):
        keyframe_dir = args.output_dir / clip_to_keyframe_dir(video_path)
        ok = extract_i_frames(
            video_path=video_path,
            output_dir=keyframe_dir,
            ffmpeg_binary=ffmpeg_binary,
            overwrite=args.overwrite,
        )
        if not ok and keyframe_dir.exists() and not any(keyframe_dir.iterdir()):
            keyframe_dir.rmdir()
        success_count += int(ok)
        status = "done" if ok else "failed"
        print(f"[{idx}/{len(videos)}] {status}: {video_path.name} -> {keyframe_dir}")

    print(f"Processed {success_count}/{len(videos)} clips successfully.")


if __name__ == "__main__":
    main()
