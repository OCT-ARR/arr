#!/usr/bin/env python3
"""Train RLOO or the optional PPO baseline with the shared FACES reward."""
import argparse
import json
import math
import os
import random
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))


def hidden_size(model):
    config = model.config
    text = getattr(config, 'text_config', None)
    value = getattr(text, 'hidden_size', None) or getattr(config, 'hidden_size', None)
    if not value:
        raise ValueError('Cannot infer policy hidden size for PPO value head')
    return int(value)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--method', choices=['rloo', 'ppo'], required=True)
    parser.add_argument('--config', type=Path, default=ROOT / 'configs/optimization_baselines.json')
    parser.add_argument('--output_dir', type=Path)
    parser.add_argument('--max_steps', type=int, default=0, help='0 runs the complete three-epoch protocol')
    parser.add_argument('--validate_only', action='store_true')
    args = parser.parse_args()
    if args.max_steps < 0:
        parser.error('--max_steps must be nonnegative')
    args.config = args.config.resolve()
    os.chdir(ROOT)
    from experiments.optimization_baselines import common as C
    from experiments.optimization_baselines.objectives import (
        generalized_advantages, leave_one_out, ppo_loss)
    from src.grpo.faces_grpo import train_faces_grpo as T
    config = C.load_config(args.config, args.method)
    cfg = C.train_config(config)
    if cfg.group_size < 2:
        raise ValueError('RLOO/PPO comparison requires group_size >= 2')
    if Path(cfg.train_file).resolve() == Path(cfg.val_file).resolve():
        raise ValueError('Training and validation files must differ')
    dataset = T.JsonlConversationDataset(cfg.train_file)
    if not len(dataset):
        raise ValueError('Training dataset is empty')
    total_batches = math.ceil(len(dataset) / cfg.batch_size) * cfg.epochs
    if args.max_steps:
        total_batches = min(total_batches, args.max_steps)
    if args.validate_only:
        print(json.dumps({'method': args.method, 'samples': len(dataset),
                          'rollout_batches': total_batches}))
        return

    import torch
    from transformers import get_cosine_schedule_with_warmup
    T.set_seed(cfg.seed)
    base, processor = T.build_policy_model_and_processor(cfg)
    model = T.create_new_lora_model(base, cfg)
    C.disable_dropout(model)
    value_head = None
    parameters = [p for p in model.parameters() if p.requires_grad]
    if args.method == 'ppo':
        value_head = torch.nn.Linear(hidden_size(model), 1, device=cfg.policy_device)
        parameters += list(value_head.parameters())
    method_cfg = config['methods'][args.method]
    updates = int(method_cfg['updates_per_rollout'])
    optimizer = torch.optim.AdamW(parameters, lr=cfg.learning_rate,
                                  weight_decay=cfg.weight_decay, betas=(0.9, 0.95))
    total_updates = max(1, total_batches * updates)
    scheduler = get_cosine_schedule_with_warmup(
        optimizer, int(total_updates * cfg.warmup_ratio), total_updates)
    engine = C.reward_engine(cfg)
    global_batch = 0
    stop = False
    for epoch in range(cfg.epochs):
        order = list(range(len(dataset)))
        random.Random(cfg.seed + epoch).shuffle(order)
        for offset in range(0, len(order), cfg.batch_size):
            if args.max_steps and global_batch >= args.max_steps:
                stop = True
                break
            cache = []
            batch_indices = order[offset:offset + cfg.batch_size]
            # Every rollout in the update batch is generated by the same old policy.
            for sample_index in batch_indices:
                sample = dataset[sample_index]
                inputs, images = C.prompt_inputs(processor, sample, cfg, config['max_sequence_length'])
                completions = C.generate(model, processor, inputs, cfg,
                                         config['max_sequence_length'], cfg.group_size)
                texts = [processor.tokenizer.decode(x, skip_special_tokens=True) for x in completions]
                scores = torch.tensor([float(x.total) for x in
                    engine.score_completions(sample, texts, images)], dtype=torch.float32)
                if scores.numel() != cfg.group_size or not torch.isfinite(scores).all():
                    raise ValueError(f'Invalid rollout rewards for sample {sample_index}')
                prompt_record = {'inputs': T._tensor_tree_to_cpu(inputs), 'rollouts': []}
                old_records = []
                for completion in completions:
                    item = C.sequence(inputs, completion, cfg, config['max_sequence_length'])
                    model.eval()
                    with torch.no_grad():
                        old_logp, old_values = C.forward(model, item, cfg.policy_device, value_head)
                        with model.disable_adapter():
                            reference_logp, _ = C.forward(model, item, cfg.policy_device)
                    old_records.append((completion, old_logp.cpu(), reference_logp.cpu(),
                                        None if old_values is None else old_values.cpu()))
                if args.method == 'rloo':
                    centered = leave_one_out(scores)
                    for group_index, (completion, old_logp, reference_logp, _) in enumerate(old_records):
                        # The terminal FACES signal uses leave-one-out centering; the
                        # reference-policy KL remains a token-level control cost.
                        future_kl = torch.flip(torch.cumsum(torch.flip(
                            old_logp - reference_logp, dims=[0]), dim=0), dims=[0])
                        advantage = centered[group_index] - cfg.kl_beta * future_kl
                        prompt_record['rollouts'].append({
                            'completion': completion, 'advantage': advantage})
                else:
                    for group_index, (completion, old_logp, reference_logp, old_values) in enumerate(old_records):
                        token_rewards = -cfg.kl_beta * (old_logp - reference_logp)
                        token_rewards[-1] += scores[group_index]
                        advantage, returns = generalized_advantages(
                            token_rewards, old_values, method_cfg['gae_gamma'], method_cfg['gae_lambda'])
                        prompt_record['rollouts'].append({
                            'completion': completion, 'old_logp': old_logp,
                            'old_values': old_values, 'advantage': advantage, 'returns': returns})
                cache.append(prompt_record)

            if args.method == 'ppo':
                all_advantages = torch.cat([r['advantage'] for p in cache for r in p['rollouts']])
                mean, std = all_advantages.mean(), all_advantages.std(unbiased=False).clamp_min(1e-8)
                for prompt in cache:
                    for rollout in prompt['rollouts']:
                        rollout['advantage'] = (rollout['advantage'] - mean) / std

            rollout_count = sum(len(x['rollouts']) for x in cache)
            for update_index in range(updates):
                optimizer.zero_grad(set_to_none=True)
                total_loss = 0.0
                for prompt in cache:
                    inputs = T._tensor_tree_to_device(prompt['inputs'], cfg.policy_device)
                    for rollout in prompt['rollouts']:
                        item = C.sequence(inputs, rollout['completion'], cfg,
                                          config['max_sequence_length'])
                        model.train()
                        logp, values = C.forward(model, item, cfg.policy_device, value_head)
                        if args.method == 'rloo':
                            loss = -(logp * rollout['advantage'].to(cfg.policy_device).detach()).mean()
                        else:
                            loss = ppo_loss(
                                logp, rollout['old_logp'].to(cfg.policy_device),
                                rollout['advantage'].to(cfg.policy_device).detach(), values,
                                rollout['old_values'].to(cfg.policy_device),
                                rollout['returns'].to(cfg.policy_device).detach(),
                                method_cfg['clip_epsilon'], method_cfg['value_clip_epsilon'],
                                method_cfg['value_loss_coefficient'])
                        if not torch.isfinite(loss):
                            raise FloatingPointError('Non-finite online objective')
                        (loss / rollout_count).backward()
                        total_loss += float(loss.detach())
                torch.nn.utils.clip_grad_norm_(parameters, cfg.max_grad_norm)
                optimizer.step()
                scheduler.step()
                print(f'method={args.method} epoch={epoch + 1}/{cfg.epochs} '
                      f'batch={global_batch + 1}/{total_batches} update={update_index + 1}/{updates} '
                      f'loss={total_loss / rollout_count:.6f}', flush=True)
            global_batch += 1
        if stop:
            break

    output = (args.output_dir or ROOT / 'checkpoints' / 'optimization_baselines' / args.method).resolve()
    output.mkdir(parents=True, exist_ok=True)
    model.save_pretrained(output / 'adapter')
    processor.save_pretrained(output)
    if value_head is not None:
        torch.save(value_head.state_dict(), output / 'value_head.pt')
    (output / 'base_model_path.txt').write_text(cfg.base_model_path + '\n')
    (output / 'training_recipe.json').write_text(json.dumps({
        'method': args.method, 'rollout_batches': global_batch, 'epochs': cfg.epochs,
        'method_hyperparameters': method_cfg}, indent=2) + '\n')


if __name__ == '__main__':
    main()
